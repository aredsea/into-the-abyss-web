def main():
    # Pairs flagged as optional are not invented if a draft sentence never existed.
    from dialogue_r21_build import OUT, read_json, display_fields
    edits = []
    for cid, pairs in PAIRS.items():
        fields = dict((p, t) for p, t, _ in display_fields(read_json(OUT / f'draft2/{cid}.json')))
        for pair in pairs:
            before, after, *path = pair
            matches = [p for p, t in fields.items() if t == before and (not path or p == path[0])]
            if not matches:
                print('NOT IN DRAFT', cid, before)
                continue
            assert len(matches) == 1, (cid, before, matches)
            edits.append({'character_id': cid, 'path': matches[0], 'before': before, 'after': after,
                          'rule': '1.1·2.2·3.3·5.3·5.5',
                          'reason': '모호한 말을 구체적인 행동과 속뜻으로 풀고, 해당 인물의 어미·호칭과 장면의 호흡을 유지했다.'})
    write_json(ROOT / 'tools/dialogue_r21_2_edits.json', edits)
    print('second reading pairs', len(edits))

if __name__ == '__main__':
    main()
