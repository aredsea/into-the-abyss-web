def main():
    edits = []
    refs = {row['id']: row for row in read_json(OUT / 'kreview-5.json')}
    for rid, after, reason in DECISIONS:
        ref = refs[rid]
        cid = ref['scene_id'].split('-')[0]
        data = read_json(OUT / f'draft6/{cid}.json')
        path = re.sub(r'\[(\d+)\]', r'/\1', ref['field']).replace('.', '/')
        if '[c' in path:
            match = re.search(r'choices\[(c\d+)\]', path)
            scene = data['inn'][int(path.split('/')[1])]
            index = next(i for i, c in enumerate(scene['choices']) if c['id'] == match[1])
            path = path.replace('choices[' + match[1] + ']', 'choices/' + str(index))
        before = at(data, path)
        assert before == ref['after5'], rid
        edits.append(dict(id=rid, character_id=cid, scene_id=ref['scene_id'], path=path,
                          before=before, after=after, reason=reason, status='반영'))
    for rid, cid, path, after, reason in EXTRAS:
        data = read_json(OUT / f'draft6/{cid}.json')
        edits.append(dict(id=rid, character_id=cid, scene_id=data['inn'][int(path.split('/')[1])]['id'],
                          path=path, before=at(data, path), after=after, reason=reason, status='연관 교정'))
    write_json(OUT / 'edits6-applied.json', edits)
    build()
